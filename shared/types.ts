/* ----------------------------------------------------------------- evidence */

export const IMPLEMENTATION_STATUSES = [
  'not_started',
  'planned',
  'partially_implemented',
  'implemented',
  'inherited',
  'not_applicable',
  'alternative_implementation',
] as const;
export type ImplementationStatus = (typeof IMPLEMENTATION_STATUSES)[number];

export type ArtifactKind = 'file' | 'url' | 'diagram' | 'text';

export type ScriptLanguage = 'powershell';

/** How a collection script hands its evidence back to the app. */
export type ScriptOutputMode = 'text' | 'image';

/** Chain-of-custody detail for an artifact produced by running a collection script. */
export interface ScriptProvenance {
  language: ScriptLanguage;
  /** Verbatim script source, kept so the collection can be re-run and reviewed. */
  source: string;
  outputMode: ScriptOutputMode;
  ranAt: string;
  exitCode: number;
  durationMs: number;
  /** Machine the script ran on, recorded for the assessor. */
  host: string;
  runBy: string;
  stderr: string;
}

export interface Artifact {
  id: string;
  evidenceType: string;
  title: string;
  description: string;
  kind: ArtifactKind;
  /** Workspace-relative path, e.g. attachments/AC/AC-2_1__20260924T1530__diagram.png */
  filePath?: string;
  fileName?: string;
  mimeType?: string;
  sizeBytes?: number;
  sha256?: string;
  url?: string;
  mermaid?: string;
  body?: string;
  /** Present when the artifact was generated by a collection script rather than picked by hand. */
  script?: ScriptProvenance;
  collectedAt?: string;
  collectedBy?: string;
  recurrence?: ArtifactRecurrence;
  /** View-only: set on artifacts shown in a control that does not own them; never persisted. */
  sharedFrom?: string;
}

