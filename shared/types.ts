export type AiProvider = 'builtin' | 'azure-openai' | 'tanstack-openai';
export type AzureCloud = 'commercial' | 'government';

/** Azure OpenAI connection settings. Authentication is the signed-in user's Entra ID token (MSAL Node); no secrets are stored here. */
export interface AiSettings {
  provider: AiProvider;
  /** Azure OpenAI resource or API Management gateway base URL, e.g. https://my-gateway.azure-api.us/api */
  endpoint: string;
  /** Deployment name as created in Azure AI Foundry, not the model name. */
  deployment: string;
  apiVersion: string;
  /** Application (client) ID of the public-client Entra app registration used for sign-in. */
  clientId: string;
  /** Entra token scope; blank uses Azure OpenAI's (cognitiveservices) scope for the selected cloud. */
  tokenScope: string;
  cloud: AzureCloud;
  /** Optional Entra tenant to sign in to; blank uses the default tenant of the signed-in account. */
  tenantId: string;
  /** Null omits the parameter (some reasoning models reject it). */
  temperature: number | null;
  /** Null lets the service decide. */
  maxOutputTokens: number | null;
  timeoutSeconds: number;
  /** Per-narrative character cap when drafting from related controls; longer narratives are truncated in the prompt. */
  relatedNarrativeMaxChars: number;
  /** Ask the service to guarantee a JSON reply (`response_format: json_object`). */
  jsonMode: boolean;
  /** TanStack AI OpenAI adapter: model id, e.g. gpt-5.2. The API key is stored encrypted by the main process, never here. */
  openaiModel: string;
  /** 'azure' targets an Azure OpenAI deployment (endpoint/deployment/apiVersion above) with the stored key as `api-key`. */
  openaiService: 'openai' | 'azure';
  /** Optional OpenAI organization ID. */
  openaiOrganization: string;
  /** Optional base URL override; blank uses https://api.openai.com/v1. */
  openaiBaseUrl: string;
}

