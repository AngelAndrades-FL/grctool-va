/** The surface exposed on `window.grc` by the preload bridge. */
export interface GrcBridge {
  getWorkspace(): Promise<WorkspaceInfo>;
  loadCatalog(): Promise<Catalog>;
  loadEvidence(): Promise<EvidenceMap>;
  saveEvidence(records: EvidenceRecord[]): Promise<{ savedAt: string }>;
  deleteEvidence(controlId: string): Promise<{ ok: true }>;
  loadSettings(): Promise<AppSettings>;
  saveSettings(settings: AppSettings): Promise<AppSettings>;
  addAttachments(req: AttachmentRequest): Promise<AttachmentResult>;
  readAttachment(relPath: string): Promise<string | null>;
  revealAttachment(relPath: string): Promise<void>;
  renameAttachment(req: AttachmentRenameRequest): Promise<Pick<Artifact, 'filePath' | 'fileName'>>;
  deleteAttachments(relPaths: string[]): Promise<{ deleted: number }>;
  runScript(req: ScriptRunRequest): Promise<ScriptRunResult>;
  aiEvaluate(req: AiEvaluateRequest): Promise<AiEvaluation>;
  aiRevise(req: AiReviseRequest): Promise<AiRevision>;
  aiRelatedDraft(req: AiRelatedDraftRequest): Promise<AiRelatedDraft>;
  aiSuggestOdp(req: AiOdpSuggestRequest): Promise<AiOdpSuggestions>;
  exportFile(req: ExportRequest): Promise<{ cancelled: boolean; path?: string }>;
  exportOscalPackage(req: OscalPackageRequest): Promise<OscalPackageResult>;
  exportSopWord(req: SopExportRequest): Promise<SopExportResult>;
  /** Deletes all attachments and control data; `confirmation` must be the word DELETE. */
  wipeControlData(confirmation: string): Promise<WipeResult>;
  importOscalSsp(): Promise<OscalImportResult>;
  backupConfig(): Promise<FileActionResult>;
  restoreConfig(): Promise<FileActionResult>;
  backupDatabase(): Promise<FileActionResult>;
  restoreDatabase(): Promise<FileActionResult>;
  /** Pick a new workspace folder (null result = cancelled). Existing data is not moved. */
  chooseWorkspaceLocation(): Promise<WorkspaceInfo | null>;
  resetWorkspaceLocation(): Promise<WorkspaceInfo>;
  /** Tests the given (possibly unsaved) settings, signing in first if needed. */
  aiTestConnection(settings: AiSettings): Promise<AiConnectionTestResult>;
  /** Forgets cached Entra sign-ins so the next request signs in again. */
  aiSignOut(): Promise<void>;
  /** Opens the system browser for Entra sign-in; returns the signed-in account name. */
  aiSignIn(settings: AiSettings): Promise<string | null>;
  aiSignedInAccount(settings: AiSettings): Promise<string | null>;
  /** Stores the OpenAI API key encrypted with the OS account; it is never returned to the renderer. */
  aiSetApiKey(apiKey: string): Promise<void>;
  aiClearApiKey(): Promise<void>;
  aiHasApiKey(): Promise<boolean>;
  openWorkspaceFolder(): Promise<void>;
}

